#!/usr/bin/env bash
# One-shot environment setup for MemoryScope-OK on openKylin (or any Debian/Ubuntu-like Linux).
#
#   bash scripts/setup_openkylin.sh            # everything
#   SKIP_AGENTS=1 bash scripts/setup_openkylin.sh   # Python side only
#
# What it does (nothing outside the project, ~/.local and apt packages):
#   1. apt: python3, venv, pip, git, curl, xz-utils, CJK fonts
#   2. project .venv + pip install -e '.[dev]'
#   3. Node.js 24 user-local in ~/.local/node (npmmirror first, nodejs.org fallback)
#   4. agents user-local in ~/.local/agents: @openai/codex and @deepseek-ai/dsh, wrappers in ~/.local/bin
#   5. .env from .env.example (chmod 600) if missing — the API key is never written by this script
# It never touches ~/.codex, ~/.dsh or shell rc files.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
NODE_MAJOR=${NODE_MAJOR:-24}   # DeepSeek Harness bundles Node 24.x; Codex CLI also runs on it
PREFIX=${MEMORYSCOPE_PREFIX:-$HOME/.local}
AGENTS_DIR=$PREFIX/agents
BIN_DIR=$PREFIX/bin
NODE_DIR=$PREFIX/node

say() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m[!] %s\033[0m\n' "$*" >&2; }

say "系统信息"
cat /etc/os-release 2>/dev/null | grep -E '^(NAME|VERSION)=' || true
uname -m

say "安装系统依赖（需要 sudo）"
if command -v apt-get >/dev/null; then
  sudo apt-get update
  sudo apt-get install -y python3 python3-venv python3-pip git curl xz-utils fonts-noto-cjk
else
  warn "未找到 apt-get，请手动安装 python3 (>=3.10)、python3-venv、git、curl、xz-utils"
fi

PY=${PYTHON:-python3}
if ! "$PY" -c 'import sys; sys.exit(sys.version_info < (3, 10))'; then
  warn "$("$PY" --version) 低于 3.10，请设置 PYTHON=/path/to/python3.10+ 后重试"
  exit 1
fi

say "创建项目虚拟环境并安装 MemoryScope-OK"
cd "$ROOT"
[ -d .venv ] || "$PY" -m venv .venv
.venv/bin/python -m pip install --upgrade pip
.venv/bin/python -m pip install -e '.[dev]'
.venv/bin/memoryscope --version

if [ ! -f .env ]; then
  cp .env.example .env
  chmod 600 .env
  warn "已创建 $ROOT/.env，请自行填入 DEEPSEEK_API_KEY（脚本不会写入密钥）"
fi

if [ "${SKIP_AGENTS:-0}" = 1 ]; then
  say "SKIP_AGENTS=1，跳过 Node 与 Agent 安装"
  exit 0
fi

case "$(uname -m)" in
  x86_64|amd64) NODE_ARCH=x64 ;;
  aarch64|arm64) NODE_ARCH=arm64 ;;
  *) warn "不支持的架构 $(uname -m)"; exit 1 ;;
esac

install_node() {
  local base version tarball tmp
  for base in https://registry.npmmirror.com/-/binary/node https://nodejs.org/dist; do
    version=$(curl -fsSL --max-time 30 "$base/index.json" 2>/dev/null \
      | "$PY" -c "import json,sys; print(next(v['version'] for v in json.load(sys.stdin) if v['version'].startswith('v$NODE_MAJOR.')))" 2>/dev/null) || continue
    tarball="node-$version-linux-$NODE_ARCH.tar.xz"
    tmp=$(mktemp -d)
    if curl -fL --max-time 600 -o "$tmp/$tarball" "$base/$version/$tarball" \
       && curl -fsSL --max-time 30 -o "$tmp/SHASUMS256.txt" "$base/$version/SHASUMS256.txt" \
       && (cd "$tmp" && grep " $tarball\$" SHASUMS256.txt | sha256sum -c -); then
      rm -rf "$NODE_DIR"
      mkdir -p "$NODE_DIR"
      tar -xJf "$tmp/$tarball" -C "$NODE_DIR" --strip-components=1
      rm -rf "$tmp"
      echo "Node $version 来自 $base"
      return 0
    fi
    rm -rf "$tmp"
    warn "从 $base 下载 Node 失败，尝试下一个源"
  done
  return 1
}

say "安装 Node.js $NODE_MAJOR 到 $NODE_DIR（仅当前用户）"
if [ -x "$NODE_DIR/bin/node" ] && "$NODE_DIR/bin/node" -v | grep -q "^v$NODE_MAJOR\."; then
  echo "已存在 $("$NODE_DIR/bin/node" -v)"
else
  install_node || { warn "Node 安装失败，请检查网络后重试"; exit 1; }
fi
export PATH="$NODE_DIR/bin:$PATH"

NPM_REGISTRY=${NPM_REGISTRY:-}
if [ -z "$NPM_REGISTRY" ]; then
  if curl -fsS --max-time 10 https://registry.npmmirror.com/ >/dev/null 2>&1; then
    NPM_REGISTRY=https://registry.npmmirror.com
  else
    NPM_REGISTRY=https://registry.npmjs.org
  fi
fi

mkdir -p "$AGENTS_DIR" "$BIN_DIR"
write_wrapper() {  # name, relative path of the JS entry inside node_modules/.bin
  cat > "$BIN_DIR/$1" <<EOF
#!/bin/sh
# Generated by MemoryScope-OK setup_openkylin.sh — runs the user-local install with the user-local Node.
PATH="$NODE_DIR/bin:\$PATH" exec "$AGENTS_DIR/node_modules/.bin/$1" "\$@"
EOF
  chmod +x "$BIN_DIR/$1"
}

say "安装 Codex CLI（@openai/codex，registry: $NPM_REGISTRY）"
npm install --prefix "$AGENTS_DIR" --registry "$NPM_REGISTRY" @openai/codex
write_wrapper codex
"$BIN_DIR/codex" --version || warn "codex --version 失败"

# DeepSeek Harness: on macOS dsh ships inside the desktop app; the same CLI is published to npm as
# @deepseek-ai/dsh (MIT, bin "dsh"), with Linux x64/arm64 sandbox addons. Install that.
say "安装 DeepSeek Harness CLI（@deepseek-ai/dsh）"
if npm install --prefix "$AGENTS_DIR" --registry "$NPM_REGISTRY" @deepseek-ai/dsh; then
  write_wrapper dsh
  "$BIN_DIR/dsh" --version || warn "dsh --version 失败，请查看上方输出"
else
  warn "@deepseek-ai/dsh 安装失败：请单独安装 DeepSeek Harness，并在 .env 中设置 MEMORYSCOPE_DSH_BIN=/path/to/dsh"
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) warn "$BIN_DIR 不在 PATH 中。本次可执行：export PATH=\"$BIN_DIR:\$PATH\"（或在 .env 设置 MEMORYSCOPE_CODEX_BIN / MEMORYSCOPE_DSH_BIN）" ;;
esac

say "完成。下一步：编辑 $ROOT/.env 填入 DEEPSEEK_API_KEY，然后运行 bash scripts/run_all.sh"
